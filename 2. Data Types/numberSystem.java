public class numberSystem {
    public static void main(String[] args) {
        System.out.println(10);
        System.out.println(0b101); // Binary 101 -> 5
        System.out.println(010); // Octal 10 -> 8
        System.out.println(0x15A); // Hexadecimal 15A -> 346

        System.out.println(3e10); // 3*10^10
    }
}
