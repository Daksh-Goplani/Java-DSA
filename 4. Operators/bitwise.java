public class bitwise {
    public static void main(String[] args) {
        System.out.println(4 & 5);
        System.out.println(4 | 5);
        System.out.println(4 ^ 5);
        System.out.println(~5);
        System.out.println(5<<1); // 101 -> 1010
        System.out.println(16>>1); // 10000 -> 1000
        int a = 9;
        a += 10;
        System.out.println(a);
    }
}
