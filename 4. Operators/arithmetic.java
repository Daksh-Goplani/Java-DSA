public class arithmetic {
    public static void main(String[] args) {
        int a = 100;
        int b = 20;

        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);

        int c = 1;
        int d = 2;
        System.out.println(c++); // Post increment
        System.out.println(++c);

        char ch = 'a';
        System.out.println(ch++);
        System.out.println(++ch);
    }
}
